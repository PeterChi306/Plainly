const DICTS: Record<string, Dict> = {
  English: en,
  Spanish: es,
  "Simplified Chinese": zh,
  Vietnamese: vi,
  Korean: ko,
  Tagalog: tl,
  French: fr,
  Russian: ru,
};

const KEY = "plainly-language";
const listeners = new Set<() => void>();

// First visit: the browser's own language, if Plainly speaks it.
function guess() {
  if (typeof navigator === "undefined") return "English";
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.toLowerCase().split("-")[0];
    const match = LANGUAGES.find((l) => l.locale.toLowerCase().split("-")[0] === base || (base === "tl" && l.id === "Tagalog"));
    if (match) return match.id;
  }
  return "English";
}

function read() {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored && stored in DICTS) return stored;
  } catch {
    // Private windows: fall back to the browser's language.
  }
  return guess();
}

function subscribe(fn: () => void) {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

export function useLanguage() {
  const language = useSyncExternalStore(subscribe, read, () => "English");
  const setLanguage = useCallback((next: string) => {
    try {
      localStorage.setItem(KEY, next);
    } catch {}
    listeners.forEach((fn) => fn());
  }, []);
  return { language, setLanguage, t: DICTS[language] ?? en };
}

export const useT = () => useLanguage().t;

/** The current language's locale, for dates. */
export function currentLocale() {
  if (typeof window === "undefined") return "en-US";
  return LANGUAGES.find((l) => l.id === read())?.locale ?? "en-US";
}
